"""Generate hooks.S (XS1 assembly for xas): one instruction per line, unique labels.
See the comments in the generated file for what each hook does."""
import sys

NI_EP_IN_INIT, NI_EP_IN_SEND, NI_EP_IN_TOKEN = 0x130cc, 0x13104, 0x13114
NI_EP_OUT_INIT, NI_EP_OUT_ARM, NI_EP_OUT_TOKEN = 0x12fe8, 0x13020, 0x13034   # (s,chan,size,maxpkt) (s,buf,size) (s,tok,buf,size)
NI_SET_REPORT = 0x12c74   # (chanend a20, buf, len, 0xc8): command 0x18 to the panel controller
RX = 0x200
REPORTS = ((2, 3), (0, 95), (1, 41))   # (mg_buf index, length): feature 0xF1 first, then LEDs
out = []
cnt = [0]


def e(*lines): out.extend(lines)


def ldaddr(a):
    assert a % 2 == 0 and (a >> 1) < 0x10000
    e("    ldc r11, 0x%x" % (a >> 1), "    shl r11, r11, 1")


def call_blob(fn):
    # Interrupts stay ENABLED: NI's USB core pumps endpoint data through this thread's interrupt
    # handlers in real time (0x14d94 IN, 0x14dd4 OUT). Masking them here (as stage 3 did) made the
    # USB core miss its bus timing -> the Z2 dropped off the bus. The handlers no longer read dp
    # (patch_stage2.py ISR_SITES), so they are safe while dp/cp point at the blob.
    e("    ldaw r11, dp[0]", "    stw r11, sp[2]",
      "    ldaw r11, cp[0]", "    stw r11, sp[3]",
      "    ldap r11, _dp", "    set dp, r11",
      "    ldap r11, _cp", "    set cp, r11",
      "    bl %s" % fn,
      "    ldw r11, sp[2]", "    set dp, r11",
      "    ldw r11, sp[3]", "    set cp, r11")


def func(name, glob=True):
    if glob: e("    .globl %s" % name)
    e("    .align 2", "    .cc_top %s.function, %s" % (name, name), "%s:" % name)


def endf(name): e("    .cc_bottom %s.function" % name, "")


e("/* generated by gen_hooks.py - do not edit */",
  "/* patched call sites (core 1): 0x12d5e bl 0x130cc -> z2_hook_init,",
  "   0x12c6c bl 0x13104 -> z2_hook_report, 0x12e62 bl 0x13114 -> z2_hook_token */",
  "    .section .dp.bss, \"awd\", @nobits", "    .align 4",
  "    .globl z2_midi_ep", "z2_midi_ep:", "    .space 24",
  "    .globl z2_midi_busy", "z2_midi_busy:", "    .space 4",
  "    .align 4", "    .globl z2_midi_buf", "z2_midi_buf:", "    .space 64",
  "    .globl z2_midi_out", "z2_midi_out:", "    .space 24",
  "    .align 4", "    .globl z2_midi_rx", "z2_midi_rx:", "    .space %d" % RX,
  "    .text", "")

# hook_init: original HID IN init, then MIDI IN endpoint on a22 (caller sp[0x84])
func("z2_hook_init")
e("    entsp 8", "    stw r4, sp[4]", "    stw r5, sp[5]")
ldaddr(NI_EP_IN_INIT); e("    bla r11")
# NI's ECM mode (caller sp[0x86] != 0) owns a22/a24 itself: then stay out completely
# (busy = 1 so z2_midi_kick never sends; the endpoint structs stay zero, no token matches)
e("    ldw r0, sp[0x%x]" % (8 + 0x86), "    bf r0, .Linit_midi",
  "    ldap r11, z2_midi_busy", "    ldc r0, 1", "    stw r0, r11[0]",
  "    ldc r0, 0", "    ldw r4, sp[4]", "    ldw r5, sp[5]", "    retsp 8",
  ".Linit_midi:")
e("    ldw r1, sp[0x%x]" % (8 + 0x84))
e("    ldap r11, z2_midi_ep", "    add r0, r11, 0", "    ldc r2, 0x40", "    ldc r3, 0x40")
ldaddr(NI_EP_IN_INIT); e("    bla r11")
e("    ldap r11, z2_midi_busy", "    ldc r0, 0", "    stw r0, r11[0]")
# MIDI OUT endpoint (EP 0x03) on a24 = caller sp[0x85], then arm the first receive
e("    ldw r1, sp[0x%x]" % (8 + 0x85))
e("    ldap r11, z2_midi_out", "    add r0, r11, 0", "    ldc r2, 0x%x" % RX, "    ldc r3, 0x%x" % RX)
ldaddr(NI_EP_OUT_INIT); e("    bla r11")
e("    ldap r11, z2_midi_out", "    add r0, r11, 0", "    ldap r11, z2_midi_rx", "    add r1, r11, 0",
  "    ldc r2, 0x%x" % RX)
ldaddr(NI_EP_OUT_ARM); e("    bla r11")
call_blob("mg_init")
e("    ldc r0, 0", "    ldw r4, sp[4]", "    ldw r5, sp[5]", "    retsp 8")
endf("z2_hook_init")

# midi_kick: if idle and packets queued, start an IN transfer
func("z2_midi_kick")
e("    entsp 6", "    ldap r11, z2_midi_busy", "    ldw r0, r11[0]", "    bt r0, .Lkick_out",
  "    ldap r11, z2_midi_buf", "    add r0, r11, 0")
call_blob("mg_next")
e("    bf r0, .Lkick_out", "    add r1, r0, 0",
  "    ldap r11, z2_midi_busy", "    ldc r0, 1", "    stw r0, r11[0]",
  "    ldap r11, z2_midi_buf", "    add r2, r11, 0",
  "    ldap r11, z2_midi_ep", "    add r0, r11, 0", "    ldc r3, 0x40")
ldaddr(NI_EP_IN_SEND); e("    bla r11")
e(".Lkick_out:", "    retsp 6")
endf("z2_midi_kick")

# hook_report: original HID send, then translate the report and kick MIDI
func("z2_hook_report")
e("    entsp 8", "    stw r4, sp[4]", "    stw r5, sp[5]", "    stw r6, sp[6]",
  "    add r4, r1, 0", "    add r5, r2, 0")
ldaddr(NI_EP_IN_SEND); e("    bla r11", "    stw r0, sp[7]", "    add r0, r5, 0", "    add r1, r4, 0")
call_blob("mg_report")
e("    bl z2_midi_kick", "    ldw r0, sp[7]", "    ldw r4, sp[4]", "    ldw r5, sp[5]", "    ldw r6, sp[6]", "    retsp 8")
endf("z2_hook_report")

# send_reports: r0 = dirty mask from mg_midi / mg_pending; sends the LED reports to the panel
# controller. Only called from z2_hook_token, so r6 still holds a20 (fn_12cac keeps it there).
func("z2_send_reports")
e("    entsp 6", "    stw r5, sp[5]", "    add r5, r0, 0")
for idx, ln in REPORTS:
    bit = {0: 1, 1: 2, 2: 4}[idx]; skip = ".Lrep_skip%d" % idx
    e("    ldc r0, %d" % bit, "    and r0, r5, r0", "    bf r0, %s" % skip, "    ldc r0, %d" % idx)
    call_blob("mg_buf")
    e("    add r1, r0, 0", "    add r0, r6, 0", "    ldc r2, %d" % ln, "    ldc r3, 0xc8")
    ldaddr(NI_SET_REPORT); e("    bla r11", "%s:" % skip)
e("    ldw r5, sp[5]", "    retsp 6")
endf("z2_send_reports")

# hook_token: MIDI completion tokens handled here, others go to NI unchanged.
# Called from fn_12cac, whose r6 holds a20 (panel-controller channel) for the whole loop.
func("z2_hook_token")
e("    entsp 10", "    stw r4, sp[4]", "    stw r5, sp[5]",
  "    ldap r11, z2_midi_out", "    ldw r4, r11[4]",
  "    zext r4, 8", "    eq r4, r4, r1", "    bt r4, .Ltok_out_ep",
  "    ldap r11, z2_midi_ep", "    ldw r4, r11[4]",
  "    zext r4, 8", "    eq r4, r4, r1", "    bt r4, .Ltok_midi")
ldaddr(NI_EP_IN_TOKEN); e("    bla r11", "    ldw r4, sp[4]", "    ldw r5, sp[5]", "    retsp 10")
# --- MIDI OUT (host -> Z2) ---
e(".Ltok_out_ep:", "    ldap r11, z2_midi_out", "    add r0, r11, 0", "    ldap r11, z2_midi_rx",
  "    add r2, r11, 0", "    ldc r3, 0x%x" % RX)
ldaddr(NI_EP_OUT_TOKEN); e("    bla r11")
# r0 > 0: complete, r0 bytes; r0 == 0 and [2] >= [1]: buffer full ([1] bytes); r0 < 0: error
e("    add r4, r0, 0", "    ldc r1, 0", "    lss r1, r1, r4", "    bt r1, .Lrx_have",
  "    bt r4, .Lrx_rearm",                       # negative: error -> just re-arm
  "    ldap r11, z2_midi_out", "    ldw r1, r11[2]",
  "    bf r1, .Lrx_rearm",                       # [2] == 0: zero-length packet -> re-arm (review fix)
  "    ldw r2, r11[1]", "    lsu r1, r1, r2",
  "    bt r1, .Ltok_done",                       # 0 < [2] < [1]: NI re-armed for a multi-packet transfer
  "    add r4, r2, 0",                           # [2] >= [1]: buffer full, process [1] bytes
  ".Lrx_have:",
  "    ldap r11, z2_midi_rx", "    add r0, r11, 0", "    add r1, r4, 0")
call_blob("mg_midi")
e("    bl z2_send_reports")
e(".Lrx_rearm:", "    ldap r11, z2_midi_out", "    add r0, r11, 0", "    ldap r11, z2_midi_rx",
  "    add r1, r11, 0", "    ldc r2, 0x%x" % RX)
ldaddr(NI_EP_OUT_ARM); e("    bla r11")
e(".Ltok_done:", "    ldc r0, 0", "    ldw r4, sp[4]", "    ldw r5, sp[5]", "    retsp 10")
# --- MIDI IN completion ---
e(".Ltok_midi:", "    ldap r11, z2_midi_ep", "    add r0, r11, 0", "    ldap r11, z2_midi_buf",
  "    add r2, r11, 0", "    ldc r3, 0x40")
ldaddr(NI_EP_IN_TOKEN); e("    bla r11")
e("    ldc r1, 0", "    lss r1, r1, r0", "    bf r1, .Ltok_out",
  "    ldap r11, z2_midi_busy", "    ldc r0, 0", "    stw r0, r11[0]", "    bl z2_midi_kick")
call_blob("mg_pending")                       # LEDs the panel side changed (pad layers)
e("    bl z2_send_reports",
  ".Ltok_out:", "    ldc r0, 0", "    ldw r4, sp[4]", "    ldw r5, sp[5]", "    retsp 10")
endf("z2_hook_token")

# _start: entry for the -nostartfiles link (never runs on the device). It only references the
# hooks so the linker keeps them; the hooks reference the mg_* functions. Without crt/libc start-up
# the blob is ~600 bytes smaller (it has to fit the ECM pool).
func("_start")
e("    ldap r11, z2_hook_init", "    ldap r11, z2_hook_report", "    ldap r11, z2_hook_token",
  "    waiteu")
endf("_start")

open(sys.argv[1] if len(sys.argv) > 1 else "hooks.S", "w").write("\n".join(out) + "\n")
